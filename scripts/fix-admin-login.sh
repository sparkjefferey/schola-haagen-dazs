#!/usr/bin/env bash
# ============================================================
#  沙藏学馆 · 管理员登录问题一键处理（服务器本地执行）
#
#  流程：只读诊断 → 给你看关键结论 → 你自己决定要不要重置口令
#
#  用法（在服务器项目目录里）：
#      cd /opt/schola-haagen-dazs
#      git pull
#      bash scripts/fix-admin-login.sh
#
#  全程不动论文/论坛/用户数据；重置口令前会自动备份数据库。
# ============================================================
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"

echo "############################################"
echo "#  沙藏学馆 · 管理员登录问题一键处理        #"
echo "############################################"
echo ""

# ---------- 第一步：只读诊断 ----------
bash "$HERE/diagnose-login.sh"

echo ""
echo "############################################"
echo "#  怎么看懂上面的结果（三条重点）           #"
echo "############################################"
echo " 1) C 段「用户总数」和账号的「建于」时间："
echo "    如果总数比你记得的少很多、且建于时间很新（就是重启那天），"
echo "    说明数据库被重新初始化过 —— 老数据已经不在了，改口令只是给新库设口令。"
echo " 2) D 段有没有失败计数：有就说明你可能只是被暂时锁住，口令本身没错。"
echo " 3) C 段 role 是不是 admin、root 是不是 1：不是的话，即使口令对也进不了后台。"
echo ""

# ---------- 第二步：问要不要重置 ----------
printf '现在要重置哪个账号的口令？（直接回车 = rector）: '
read -r TARGET
TARGET="${TARGET:-rector}"

printf '确认重置账号「%s」的口令？会随机生成新口令并踢掉它的全部在线会话。输入 yes 继续: ' "$TARGET"
read -r CONFIRM
if [ "$CONFIRM" != "yes" ]; then
  echo ""
  echo "已取消，没有改动任何数据。"
  exit 0
fi

echo ""
bash "$HERE/reset-admin-password.sh" "$TARGET"

echo ""
echo "############################################"
echo "#  下一步                                   #"
echo "############################################"
echo " 1) 用上面的新口令登录（如果还登不上，说明根因不是口令，回到诊断结果看 D 段/C 段）"
echo " 2) 登录后到个人页把它改成你记得住的口令"
echo " 3) 浏览器里删掉旧保存的口令，避免下次又填错"
